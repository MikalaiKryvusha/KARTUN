"""make-vector-icon.py - KARTUN's own VECTOR launcher icon: a glass heart split by a laser line - the left half tiled
with checker glass squares (pixels), the right half perfectly smooth and glossy. The owner's order, chat 2026-10-14
≈ 18:33 +03:00: «Нарисуй вообще свою векторную иконку. Сердце, как нам ГПТ пытался рисовать. И правая и левая части
гладкие. Стеклянные. Но левая - покрыта шахматными квадратиками стекла - а левая идеально гладкая, блеслящая»
(read as: the RIGHT half is the shiny one - his earlier «слева пиксели, справа от черты-лазера - гладкое»).

One geometry, two renderings: an Android VectorDrawable (foreground + monochrome of the adaptive icon, 108 x 108 dp
viewport, the OS mask shows the inner 72 dp) and an SVG twin used only for the preview sheet on the PC.
The heart reaches 27 dp from the centre - the size the owner picked («B», 2026-10-14 ≈ 15:37).
[TESTED: 2026-10-14 · rendered by Android on the Titan, splash and app list - testcases/reports/2026-10-14_F2_screens_slice1.md run 14]

Usage (from the project root): python tools/make-vector-icon.py [--apply]
  without --apply: writes design/icon/heart_vector.svg and res/drawable/ic_launcher_heart*.xml (not referenced yet);
  with --apply:    also points res/mipmap-anydpi/ic_launcher*.xml at the vector drawables.
"""
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
C = 54.0  # centre of the 108 dp adaptive-icon canvas

# Heart outline (cubic Béziers), symmetric about x = 54; bottom tip at y = 79, lobes reach x = 28 / 80.
HEART = ("M54,79 C47,73 28,61 28,45 C28,36.5 34.5,30 42.5,30 C47.5,30 51.5,32.8 54,37 "
         "C56.5,32.8 60.5,30 65.5,30 C73.5,30 80,36.5 80,45 C80,61 61,73 54,79 Z")
LEFT_HALF = "M0,0 H54 V108 H0 Z"
RIGHT_HALF = "M54,0 H108 V108 H54 Z"

PINK = "#FF1A8C"
TILE = 4.0                      # checker glass square, dp
# Glass tones of the tiles, dark to bright. Each tile takes one at random - the owner, 2026-10-14 ≈ 19:10: «пиксели слева
# нужно рандомно ярче темнее хаос». The seed is fixed, so every rebuild draws the same chaos (no drift between runs).
TILE_TONES = ["#6E0038", "#8E0049", "#B8005F", "#E0087A", "#FF3D9E", "#FF6BB5", "#FF9ACB"]
TILE_SEED = 14
GLOW = "#FF1A8C"


def squares():
    """Glass squares covering the left half of the heart's bounding box (clipped to the heart later), each of a random
    tone; a fresh seeded generator per call, so every caller gets the same tiles in the same order."""
    rnd = random.Random(TILE_SEED)
    out = []
    y = 28.0
    row = 0
    while y < 80:
        x = 26.0
        col = 0
        while x < 54:
            out.append((x, y, rnd.choice(TILE_TONES)))
            x += TILE
            col += 1
        y += TILE
        row += 1
    return out


def rect(x, y, w, h):
    return f"M{x:g},{y:g}h{w:g}v{h:g}h{-w:g}z"


def bevels():
    """Light (top + left) and dark (bottom + right) edge strips of every glass tile, as two path strings."""
    g, b = 0.18, 0.6  # gap between tiles, bevel width
    lit = "".join(rect(x + g, y + g, TILE - 2 * g, b) + rect(x + g, y + g + b, b, TILE - 2 * g - b) for x, y, _ in squares())
    dark = "".join(rect(x + g, y + TILE - g - b, TILE - 2 * g, b) + rect(x + TILE - g - b, y + g, b, TILE - 2 * g - b) for x, y, _ in squares())
    return lit, dark


# ---------------------------------------------------------------- Android VectorDrawable
def gradient_xml(kind, attrs, stops):
    st = "\n".join(f'                    <item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    a = " ".join(f'android:{k}="{v}"' for k, v in attrs.items())
    return f"""            <aapt:attr name="android:fillColor">
                <gradient android:type="{kind}" {a}>
{st}
                </gradient>
            </aapt:attr>"""


def foreground_xml():
    tiles_by_colour = {}
    for x, y, c in squares():
        tiles_by_colour.setdefault(c, []).append(rect(x + 0.18, y + 0.18, TILE - 0.36, TILE - 0.36))
    tiles = "\n".join(f'            <path android:fillColor="{c}" android:pathData="{"".join(p)}" />' for c, p in tiles_by_colour.items())
    # Each square is a glass tile: a light bevel along its top and left edges, a dark one along the bottom and right.
    lit, dark = bevels()
    tiles += f'\n            <path android:fillColor="#59FFFFFF" android:pathData="{lit}" />'
    tiles += f'\n            <path android:fillColor="#40000000" android:pathData="{dark}" />'
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make-vector-icon.py - edit the script, not this file. KARTUN's vector glass heart:
     checker glass on the left, smooth gloss on the right, a laser line between them. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <!-- soft pink glow behind the heart -->
    <path android:pathData="M54,54m-34,0a34,34 0 1,0 68,0a34,34 0 1,0 -68,0">
{gradient_xml("radial", {"centerX": "54", "centerY": "55", "gradientRadius": "34"}, [("0", "#66FF1A8C"), ("0.55", "#26FF1A8C"), ("1", "#00FF1A8C")])}
    </path>
    <!-- the dark glass body of the heart (seen through the gaps between the tiles) -->
    <path android:pathData="{HEART}" android:fillColor="#3A0020" />
    <!-- LEFT: checker glass squares, clipped to the heart and to the left half -->
    <group>
        <clip-path android:pathData="{HEART}" />
        <group>
            <clip-path android:pathData="{LEFT_HALF}" />
{tiles}
            <!-- glass sheen over the tiles -->
            <path android:pathData="{HEART}">
{gradient_xml("linear", {"startX": "30", "startY": "30", "endX": "54", "endY": "70"}, [("0", "#66FFFFFF"), ("0.45", "#14FFFFFF"), ("1", "#00FFFFFF")])}
            </path>
        </group>
        <!-- RIGHT: smooth glossy glass -->
        <group>
            <clip-path android:pathData="{RIGHT_HALF}" />
            <path android:pathData="{HEART}">
{gradient_xml("linear", {"startX": "56", "startY": "30", "endX": "76", "endY": "74"}, [("0", "#FF8CC8"), ("0.45", "#FF1A8C"), ("1", "#9E0052")])}
            </path>
            <!-- specular highlight on the right lobe -->
            <path android:pathData="M68,36.5m-8,0a8,4.6 0 1,0 16,0a8,4.6 0 1,0 -16,0">
{gradient_xml("radial", {"centerX": "68", "centerY": "36.5", "gradientRadius": "8"}, [("0", "#E6FFFFFF"), ("0.6", "#40FFFFFF"), ("1", "#00FFFFFF")])}
            </path>
            <!-- a long soft reflection down the right side -->
            <path android:pathData="M74.5,44 C75.5,52 71,61 63,68.5 C69,60 72,52 72.6,44 Z" android:fillColor="#40FFFFFF" />
        </group>
    </group>
    <!-- glass rim -->
    <path android:pathData="{HEART}" android:strokeColor="#B3FF9ED2" android:strokeWidth="0.9" android:fillColor="#00000000" />
    <!-- the laser line between the halves: a pink glow and a white core -->
    <path android:pathData="M54,33 V81" android:strokeColor="#99FF1A8C" android:strokeWidth="2.6" android:strokeLineCap="round" />
    <path android:pathData="M54,33 V81" android:strokeColor="#FFFFFFFF" android:strokeWidth="0.7" android:strokeLineCap="round" />
</vector>
"""


def monochrome_xml():
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make-vector-icon.py - the themed (monochrome) layer: the heart's silhouette with the laser cut. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="{HEART}" android:fillColor="#FFFFFFFF" />
    <path android:pathData="M54,36 V80" android:strokeColor="#FF000000" android:strokeWidth="1.4" />
</vector>
"""


# ---------------------------------------------------------------- SVG twin (preview only)
def svg():
    tiles = "".join(f'<rect x="{x + 0.18:g}" y="{y + 0.18:g}" width="{TILE - 0.36:g}" height="{TILE - 0.36:g}" fill="{c}"/>' for x, y, c in squares())
    lit, dark = bevels()
    tiles += f'<path d="{lit}" fill="#fff" fill-opacity=".35"/><path d="{dark}" fill="#000" fill-opacity=".25"/>'
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">
<defs>
  <clipPath id="heart"><path d="{HEART}"/></clipPath>
  <clipPath id="left"><path d="{LEFT_HALF}"/></clipPath>
  <clipPath id="right"><path d="{RIGHT_HALF}"/></clipPath>
  <radialGradient id="glow" gradientUnits="userSpaceOnUse" cx="54" cy="55" r="34"><stop offset="0" stop-color="#FF1A8C" stop-opacity=".4"/><stop offset=".55" stop-color="#FF1A8C" stop-opacity=".15"/><stop offset="1" stop-color="#FF1A8C" stop-opacity="0"/></radialGradient>
  <linearGradient id="sheen" gradientUnits="userSpaceOnUse" x1="30" y1="30" x2="54" y2="70"><stop offset="0" stop-color="#fff" stop-opacity=".4"/><stop offset=".45" stop-color="#fff" stop-opacity=".08"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></linearGradient>
  <linearGradient id="gloss" gradientUnits="userSpaceOnUse" x1="56" y1="30" x2="76" y2="74"><stop offset="0" stop-color="#FF8CC8"/><stop offset=".45" stop-color="#FF1A8C"/><stop offset="1" stop-color="#9E0052"/></linearGradient>
  <radialGradient id="spec" gradientUnits="userSpaceOnUse" cx="68" cy="36.5" r="8"><stop offset="0" stop-color="#fff" stop-opacity=".9"/><stop offset=".6" stop-color="#fff" stop-opacity=".25"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>
</defs>
<rect width="108" height="108" fill="#0F000C"/>
<circle cx="54" cy="54" r="34" fill="url(#glow)"/>
<path d="{HEART}" fill="#3A0020"/>
<g clip-path="url(#heart)">
  <g clip-path="url(#left)">{tiles}<path d="{HEART}" fill="url(#sheen)"/></g>
  <g clip-path="url(#right)"><path d="{HEART}" fill="url(#gloss)"/><ellipse cx="68" cy="36.5" rx="8" ry="4.6" fill="url(#spec)"/>
    <path d="M74.5,44 C75.5,52 71,61 63,68.5 C69,60 72,52 72.6,44 Z" fill="#fff" fill-opacity=".25"/></g>
</g>
<path d="{HEART}" fill="none" stroke="#FF9ED2" stroke-opacity=".7" stroke-width=".9"/>
<path d="M54,33 V81" stroke="#FF1A8C" stroke-opacity=".6" stroke-width="2.6" stroke-linecap="round"/>
<path d="M54,33 V81" stroke="#fff" stroke-width=".7" stroke-linecap="round"/>
</svg>
"""


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make-vector-icon.py (apply mode) - the vector glass heart (edit the script, not this file).
     The raster icon from icon_v3 stays in mipmap-*/ (tools/make-icon.py) for a switch back. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_heart" />
    <monochrome android:drawable="@drawable/ic_launcher_heart_mono" />
</adaptive-icon>
"""


def main():
    apply = "--apply" in sys.argv
    out = ROOT / "design" / "icon"
    (out / "heart_vector.svg").write_text(svg(), encoding="utf-8", newline="\n")
    drawable = ROOT / "app" / "src" / "main" / "res" / "drawable"
    (drawable / "ic_launcher_heart.xml").write_text(foreground_xml(), encoding="utf-8", newline="\n")
    (drawable / "ic_launcher_heart_mono.xml").write_text(monochrome_xml(), encoding="utf-8", newline="\n")
    print("written design/icon/heart_vector.svg, res/drawable/ic_launcher_heart.xml, ic_launcher_heart_mono.xml")
    if apply:
        for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
            (ROOT / "app" / "src" / "main" / "res" / "mipmap-anydpi" / name).write_text(ADAPTIVE, encoding="utf-8", newline="\n")
        print("applied: mipmap-anydpi/ic_launcher*.xml -> the vector heart")


if __name__ == "__main__":
    main()
